local function GetLocaleString(langId, langStr)
    if (HermesLocalizationData[langId] ~= nil) and (HermesLocalizationData[langId][langStr] ~= nil) then
        return HermesLocalizationData[langId][langStr]
    end

    return HermesLocalizationData["en"][langStr]
end

function Hermes.GetDefaultLocaleString(langStr)
    return GetLocaleString(GetCVar("language.2"), langStr)
end