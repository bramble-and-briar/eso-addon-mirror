    internal static async Task WriteRecordsAddonAsync(
        string addOnsPath,
        CapturedRecordsResponse snapshot)
    {
        ValidateCapturedRecords(snapshot);
        var addonDirectory = Path.Combine(Path.GetFullPath(addOnsPath), "DungeonScoresRecords");
        Directory.CreateDirectory(addonDirectory);

        var lua = new StringBuilder();
        AppendRecordsHeader(lua, snapshot);
        AppendCapturedRecords(lua, snapshot.Records);
        AppendPartyRecords(lua, snapshot.PartyRecords ?? []);
        AppendHighStandings(lua, snapshot.HighStandings ?? []);
        AppendRaceToBottomStandings(lua, snapshot.RaceToBottomRecords ?? []);
        AppendGuilds(lua, snapshot.Guilds ?? []);
        lua.AppendLine("}");

        await AtomicWriteAsync(Path.Combine(addonDirectory, "Records.lua"), lua.ToString());
        await AtomicWriteAsync(Path.Combine(addonDirectory, "DungeonScoresRecords.txt"), RecordsManifest);
    }

    private static void AppendRecordsHeader(StringBuilder lua, CapturedRecordsResponse snapshot)
    {
        lua.AppendLine("-- Generated by the Dungeon Scores companion. Do not edit while the companion is running.");
        lua.AppendLine("DungeonScoresRecords = DungeonScoresRecords or {}");
        lua.AppendLine("DungeonScoresRecords.Data = {");
        lua.AppendLine("    schemaVersion = 2,");
        lua.AppendLine($"    generatedAt = {DateTimeOffset.UtcNow.ToUnixTimeSeconds()},");
        lua.AppendLine("    scope = \"PC NA + PC EU\",");
        lua.AppendLine($"    worldPublicationDepth = {snapshot.WorldPublicationDepth},");
        lua.AppendLine($"    raceToBottomPublicationDepth = {snapshot.RaceToBottomPublicationDepth},");
    }

    private static void AppendCapturedRecords(StringBuilder lua, IEnumerable<CapturedRecord> records)
    {
        lua.AppendLine("    records = {");
        foreach (var record in records.OrderBy(record => record.ZoneId))
        {
            lua.AppendLine($"        [{record.ZoneId}] = {{");
            AppendCapturedRecordFields(lua, record, "            ");
            lua.AppendLine("        },");
        }
        lua.AppendLine("    },");
    }

    private static void AppendPartyRecords(StringBuilder lua, IEnumerable<CapturedRecord> records)
    {
        lua.AppendLine("    partyRecords = {");
        foreach (var zoneGroup in records.OrderBy(record => record.ZoneId)
                     .ThenBy(record => record.RunGroupSize)
                     .GroupBy(record => record.ZoneId))
        {
            lua.AppendLine($"        [{zoneGroup.Key}] = {{");
            foreach (var record in zoneGroup)
            {
                lua.AppendLine($"            [{record.RunGroupSize}] = {{");
                AppendCapturedRecordFields(lua, record, "                ");
                lua.AppendLine("            },");
            }
            lua.AppendLine("        },");
        }
        lua.AppendLine("    },");
    }

