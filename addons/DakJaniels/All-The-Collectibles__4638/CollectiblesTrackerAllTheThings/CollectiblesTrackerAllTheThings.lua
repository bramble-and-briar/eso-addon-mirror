local function CollectLeftoverCollectibleIds(excluded)
    local leftoverIds = {}
    local leftoverSeen = {}

    local function Worker(entry)
        if (type(entry) == "table") then
            if (#entry > 1) then
                LCCC.ProcessNumericTable(entry, Worker)
                return
            end
            entry = entry[1]
        end
        if (type(entry) ~= "number") then
            return
        end
        local collectibleId = math.abs(entry)
        if (not excluded[collectibleId] and not leftoverSeen[collectibleId]) then
            leftoverSeen[collectibleId] = true
            leftoverIds[#leftoverIds + 1] = collectibleId
        end
    end

    for _, sourceDef in ipairs(ALLTHETHINGS_SOURCES) do
        LCCC.ProcessNumericTable(sourceDef[2], Worker)
    end

    return leftoverIds
end

local function GetSortedNumericKeys(valueByKey)
    local keys = {}
    for key in pairs(valueByKey) do
        if (type(key) == "number") then
            keys[#keys + 1] = key
        end
    end
    table.sort(keys)
    return keys
end

