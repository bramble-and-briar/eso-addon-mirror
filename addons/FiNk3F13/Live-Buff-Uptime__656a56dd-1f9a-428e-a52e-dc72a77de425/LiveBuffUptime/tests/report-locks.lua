local env = dofile("tests/addon.lua")
local list = dofile("tests/helpers/report-console-ui.lua")(env)
local reports = LiveBuffUptimeReports
local function record(name, zone)
    return {title = name, zone = zone or "Raid", date = "20261018", clock = "12:00:00", started = 0, ended = 10,
        buffs = {{id = 61771, name = "Buff", unit = "player", covered = 5, duration = 10, percent = 50,
            members = {{name = "Player", covered = 5, duration = 10}}}}}
end
local a, b, c = record("First"), record("Second"), record("Other", "Other Area")
local saved = {uptimeHistory = {a, b, c}}
reports.Init(saved)
local bindings, definition, shown
KEYBIND_STRIP = {AddKeybindButtonGroup = function(_, group) bindings = group end, RemoveKeybindButtonGroup = function() end}
GAMEPAD_DIALOGS, SI_DIALOG_CANCEL = {BASIC = 1}, "Abbrechen"
ZO_Dialogs_RegisterCustomDialog = function(_, dialog) definition = dialog end
ZO_Dialogs_ShowGamepadDialog = function(_, data) shown = {data = data} end
reports.Open()
assert(bindings[7].visible())
bindings[7].callback()
assert(a.locked and b.locked and not c.locked, "Area selection must lock all fights of the selected entry only")
bindings[7].callback()
assert(not a.locked and not b.locked)
reports.ShowZone()
list:SetSelectedIndex(2)
assert(bindings[7].visible() and bindings[7].keybind == "UI_SHORTCUT_SECONDARY")
assert(bindings[7].name() == "Sperren" and bindings[6].enabled())
bindings[7].callback()
assert(b.locked and not a.locked and list.index == 2)
assert(list.entries[2].locked and list.entries[2].subtitle:find("Gesperrt", 1, true))
assert(bindings[7].name() == "Entsperren" and not bindings[6].enabled())
bindings[6].callback()
reports.DeleteFight(b)
assert(not shown and #saved.uptimeHistory == 3)
reports.ShowBuffs()
assert(not bindings[7].visible())
bindings[7].callback()
assert(b.locked, "Buff detail view must not toggle locks")
reports.Back()
reports.Close()
reports.Init(saved)
reports.Open()
reports.ShowZone()
list:SetSelectedIndex(2)
assert(b.locked and bindings[7].name() == "Entsperren", "Lock must survive reload of saved settings")
reports.Back()
bindings[6].callback()
assert(#shown.data.records == 1 and shown.data.records[1] == a and shown.data.protectedCount == 1)
assert(definition.mainText.text(shown):find("1 gesperrte Kaempfe bleiben erhalten.", 1, true))
reports.ToggleLock()
assert(b.locked and not a.locked, "Confirmation must block lock changes")
local newer = record("Arrived during confirmation")
reports.Save(newer)
definition.buttons[1].callback(shown)
definition.finishedCallback(shown)
assert(#saved.uptimeHistory == 3 and saved.uptimeHistory[1] == newer)
assert(saved.uptimeHistory[2] == b and b.locked, "Area deletion must preserve locked fights and newly arriving reports")
reports.DeleteZone({newer, b})
assert(#saved.uptimeHistory == 2 and saved.uptimeHistory[1] == b)
assert(not bindings[6].enabled(), "An area containing only locked fights cannot be deleted")
reports.ShowZone()
assert(bindings[7].name() == "Entsperren")
bindings[7].callback()
assert(not b.locked and bindings[6].enabled())
bindings[6].callback()
b.locked = true
definition.buttons[1].callback(shown)
definition.finishedCallback(shown)
assert(saved.uptimeHistory[1] == b, "Deletion must recheck lock state at confirmation time")
bindings[7].callback()
reports.DeleteFight(b)
assert(#saved.uptimeHistory == 1 and saved.uptimeHistory[1] == c)
assert(b.buffs[1].percent == 50 and b.buffs[1].covered == 5)
reports.Close()
print("Fight locks: native controller action, persistent marker, stable selection, detail/modal guards and protected direct/area deletion passed")
