using System.Text;
using System.Text.Json;

internal static partial class Program
{
    private const int MaximumDeliveryReceipts = 100;

    private static async Task<Dictionary<string, DeliveryReceipt>> LoadDeliveryReceiptsAsync(string path)
    {
        if (!File.Exists(path)) return new(StringComparer.Ordinal);
        try
        {
            var parsed = JsonSerializer.Deserialize(
                await File.ReadAllTextAsync(path),
                CompanionJsonContext.Default.DictionaryStringDeliveryReceipt);
            return parsed is null
                ? new(StringComparer.Ordinal)
                : new(parsed, StringComparer.Ordinal);
        }
        catch (JsonException)
        {
            return new(StringComparer.Ordinal);
        }
    }

    private static void SetDeliveryReceipt(
        Dictionary<string, DeliveryReceipt> receipts,
        QueueItem item,
        string status)
    {
        receipts[item.QueueKey] = new DeliveryReceipt(
            status, DateTimeOffset.UtcNow.ToUnixTimeSeconds());
    }

    private static async Task WriteDeliveryReceiptsAsync(
        string statePath,
        string addOnsPath,
        IReadOnlyList<QueueItem> queue,
        HashSet<string> submitted,
        Dictionary<string, DeliveryReceipt> receipts)
    {
        // Older submitted.json entries establish only that this companion handled
        // the queue key. They cannot prove a successful server response.
        foreach (var item in queue)
        {
            if (submitted.Contains(item.QueueKey) && !receipts.ContainsKey(item.QueueKey))
                SetDeliveryReceipt(receipts, item, "outcome-unknown");
        }

        var retained = receipts
            .Where(pair => pair.Value is not null
                && pair.Value.UpdatedAt > 0
                && pair.Value.Status is "delivered" or "rejected" or "retrying" or "outcome-unknown")
            .OrderByDescending(pair => pair.Value.UpdatedAt)
            .ThenBy(pair => pair.Key, StringComparer.Ordinal)
            .Take(MaximumDeliveryReceipts)
            .ToDictionary(pair => pair.Key, pair => pair.Value, StringComparer.Ordinal);
        await AtomicWriteAsync(statePath, JsonSerializer.Serialize(
            retained, CompanionJsonContext.Default.DictionaryStringDeliveryReceipt));

        var lua = new StringBuilder();
        lua.AppendLine("-- Generated by the Dungeon Scores companion. Local delivery status as of the last ESO UI load.");
        lua.AppendLine("DungeonScoresRecords = DungeonScoresRecords or {}");
        lua.AppendLine("DungeonScoresRecords.Delivery = {");
        lua.AppendLine("    schemaVersion = 1,");
        lua.AppendLine($"    generatedAt = {DateTimeOffset.UtcNow.ToUnixTimeSeconds()},");
        lua.AppendLine("    receipts = {");
        foreach (var pair in retained.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            lua.AppendLine($"        [{LuaString(pair.Key)}] = {{ status = {LuaString(pair.Value.Status)}, updatedAt = {pair.Value.UpdatedAt} }},");
        }
        lua.AppendLine("    },");
        lua.AppendLine("}");
        var directory = Path.Combine(Path.GetFullPath(addOnsPath), "DungeonScoresRecords");
        await AtomicWriteAsync(Path.Combine(directory, "Delivery.lua"), lua.ToString());
    }
}
