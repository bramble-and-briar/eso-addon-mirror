local languageSettings
local refreshCallbacks = {}

local function ResolveLanguage(value)
    local language = string.lower(tostring(value or DEFAULT_LANGUAGE)):gsub("_", "-")
    language = LANGUAGE_ALIASES[language] or language
    if not SUPPORTED_LANGUAGES[language] then
        local prefix = language:match("^([a-z][a-z])")
        language = LANGUAGE_ALIASES[prefix] or prefix
    end

    return SUPPORTED_LANGUAGES[language] and language or nil
end

local function NormalizeLanguage(value)
    return ResolveLanguage(value) or DEFAULT_LANGUAGE
end

local function NormalizeLanguagePreference(value)
    if type(value) ~= "string" or value == "" then
        return DEFAULT_LANGUAGE_PREFERENCE
    end

    if string.lower(value) == DEFAULT_LANGUAGE_PREFERENCE then
        return DEFAULT_LANGUAGE_PREFERENCE
    end

    return ResolveLanguage(value) or DEFAULT_LANGUAGE_PREFERENCE
end

local function InitializeLanguageSettings()
    local defaults = { language = DEFAULT_LANGUAGE_PREFERENCE }
    languageSettings = ZO_SavedVars:NewAccountWide(
        LANGUAGE_SAVED_VARIABLES_NAME,
        LANGUAGE_SAVED_VARIABLES_VERSION,
        nil,
        defaults,
        nil,
        INSTALLATION_WIDE
    )

    return languageSettings
end

local function RequestLanguageSettingsSave()
    local addOnManager = GetAddOnManager and GetAddOnManager()
    if addOnManager and addOnManager.RequestAddOnSavedVariablesPrioritySave then
        addOnManager:RequestAddOnSavedVariablesPrioritySave(NGear.name or "NGear")
    end
end

local gameLanguage = NormalizeLanguage(GetCVar and GetCVar("Language.2") or DEFAULT_LANGUAGE)
local languagePreference = DEFAULT_LANGUAGE_PREFERENCE
local activeLanguage = gameLanguage
local initialized = false

local function PruneTranslations()
    for language in pairs(TRANSLATIONS) do
        if language ~= DEFAULT_LANGUAGE and language ~= activeLanguage then
            TRANSLATIONS[language] = nil
        end
    end
end

local function FormatWithoutEso(text, ...)
    local arguments = { ... }
    return (text:gsub("<<[A-Za-z]?:?(%d+)>>", function(index)
        local value = arguments[tonumber(index)]
        return value == nil and "" or tostring(value)
    end))
end

function Lexicon.NormalizeLanguage(value)
    return NormalizeLanguage(value)
end

function Lexicon.GetLanguage()
    return activeLanguage
end

function Lexicon.GetGameLanguage()
    return gameLanguage
end

function Lexicon.IsSupportedLanguage(value)
    return ResolveLanguage(value) ~= nil
end

function Lexicon.Initialize()
    if initialized then
        return activeLanguage
    end

    local currentSettings = InitializeLanguageSettings()
    languagePreference = NormalizeLanguagePreference(currentSettings.language)
    currentSettings.language = languagePreference
    activeLanguage = languagePreference == DEFAULT_LANGUAGE_PREFERENCE and gameLanguage or languagePreference
    initialized = true

    for index = 1, #refreshCallbacks do
        refreshCallbacks[index]()
    end
    refreshCallbacks = {}
    PruneTranslations()

    return activeLanguage
end

function Lexicon.RegisterRefreshCallback(callback)
    if type(callback) ~= "function" then
        return
    end

    callback()
    if not initialized then
        refreshCallbacks[#refreshCallbacks + 1] = callback
    end

end

function Lexicon.LocalizedList(definitions)
    local values = {}
    Lexicon.RegisterRefreshCallback(function()
        for index, definition in ipairs(definitions) do
            if type(definition) == "table" then
                values[index] = Lexicon.Get(Unpack(definition))
            else
                values[index] = Lexicon.Get(definition)
            end
        end
    end)

    return values
end

function Lexicon.RegisterTableField(values, fieldName, definitions)
    Lexicon.RegisterRefreshCallback(function()
        for index, definition in ipairs(definitions) do
            if type(definition) == "table" then
                values[index][fieldName] = Lexicon.Get(Unpack(definition))
            else
                values[index][fieldName] = Lexicon.Get(definition)
            end
        end
    end)
end

function Lexicon.GetLanguagePreference()
    if initialized then
        languagePreference = NormalizeLanguagePreference(languageSettings.language)
    end

    return languagePreference
end

function Lexicon.GetLanguagePreferenceDefault()
    return DEFAULT_LANGUAGE_PREFERENCE
end

function Lexicon.NormalizeLanguagePreference(value)
    return NormalizeLanguagePreference(value)
end

function Lexicon.IsLanguagePreference(value)
    return type(value) == "string"
        and (string.lower(value) == DEFAULT_LANGUAGE_PREFERENCE or ResolveLanguage(value) ~= nil)
end

function Lexicon.SetLanguagePreference(value)
    if not initialized then
        return false
    end

    local normalizedValue = NormalizeLanguagePreference(value)
    languageSettings.language = normalizedValue
    languagePreference = normalizedValue
    RequestLanguageSettingsSave()

    return languageSettings.language == normalizedValue
end

function Lexicon.GetLanguageChoices()
    local choices = {}
    for index = 1, #LANGUAGE_CHOICES do
        choices[index] = LANGUAGE_CHOICES[index]
    end
    return choices
end

function Lexicon.GetLanguageChoiceNames()
    local names = {}
    for index = 1, #LANGUAGE_CHOICE_KEYS do
        names[index] = Lexicon.Get(LANGUAGE_CHOICE_KEYS[index])
    end
    return names
end

function Lexicon.Get(key, ...)
    local languageTable = TRANSLATIONS[activeLanguage] or TRANSLATIONS[DEFAULT_LANGUAGE]
    local text = languageTable[key] or TRANSLATIONS[DEFAULT_LANGUAGE][key] or tostring(key)
    if select("#", ...) == 0 then
        return text
    end

    if zo_strformat then
        return zo_strformat(text, ...)
    end

    return FormatWithoutEso(text, ...)
end

