local LCCC = LibCodesCommonCode

local function CompressCollectibleIds(collectibleIds, minRun)
    minRun = minRun or 3
    if (#collectibleIds == 0) then
        return {}
    end

    local uniqueSorted = {}
    local seenId = {}
    for _, collectibleId in ipairs(collectibleIds) do
        if (not seenId[collectibleId]) then
            seenId[collectibleId] = true
            uniqueSorted[#uniqueSorted + 1] = collectibleId
        end
    end
    table.sort(uniqueSorted)

    local compressed = {}
    local runStart = uniqueSorted[1]
    local runEnd = uniqueSorted[1]

    local function AppendRun(startId, endId)
        local runLength = endId - startId + 1
        if (runLength >= minRun) then
            compressed[#compressed + 1] = startId
            compressed[#compressed + 1] = -endId
        else
            for collectibleId = startId, endId do
                compressed[#compressed + 1] = collectibleId
            end
        end
    end

    for index = 2, #uniqueSorted do
        local collectibleId = uniqueSorted[index]
        if (collectibleId == runEnd + 1) then
            runEnd = collectibleId
        else
            AppendRun(runStart, runEnd)
            runStart = collectibleId
            runEnd = collectibleId
        end
    end
    AppendRun(runStart, runEnd)
    return compressed
end

local function AccumulateSeenCollectibleIdsFromTrackerData(seen, trackerData)
    local function Worker(entry)
        -- Match the browser: morph / fragment sets are nested numeric tables.
        if (type(entry) == "table") then
            if (#entry > 1) then
                LCCC.ProcessNumericTable(entry, Worker)
                return
            end
            entry = entry[1]
        end

        if (type(entry) == "number") then
            seen[math.abs(entry)] = true
        end
    end

    for _, source in ipairs(trackerData) do
        for j = 2, #source do
            LCCC.ProcessNumericTable(source[j], Worker)
        end
    end
end

local function BuildCollectiblesTrackerSeenIdSet()
    local seen = {}
    local trackerData = CollectiblesTracker.data
    if (trackerData.ct) then
        AccumulateSeenCollectibleIdsFromTrackerData(seen, trackerData.ct)
    end
    if (trackerData.ec) then
        AccumulateSeenCollectibleIdsFromTrackerData(seen, trackerData.ec)
    end
    return seen
end

local function FilterCollectibleList(rawList, seen)
    local flatFiltered = {}

    local function Worker(entry)
        -- Match Collectibles Tracker Browser.lua: nested numeric tables are morph / fragment sets.
        if (type(entry) == "table") then
            if (#entry > 1) then
                LCCC.ProcessNumericTable(entry, Worker)
                return
            end
            entry = entry[1]
        end
        if (type(entry) ~= "number") then
            return
        end
        -- ProcessNumericTable expands CT ranges to positive ids; abs covers any leftover end marker.
        local collectibleId = math.abs(entry)
        if (not seen[collectibleId]) then
            flatFiltered[#flatFiltered + 1] = collectibleId
        end
    end

    LCCC.ProcessNumericTable(rawList, Worker)
    return CompressCollectibleIds(flatFiltered)
end

