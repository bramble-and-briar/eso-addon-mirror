-- MANA Junk — Русский
function MANAJunk.STACKS(n)
    local m10, m100 = n % 10, n % 100
    local word
    if m10 == 1 and m100 ~= 11 then word = "стак"
    elseif m10 >= 2 and m10 <= 4 and (m100 < 12 or m100 > 14) then word = "стака"
    else word = "стаков" end
    return n .. " " .. word
end

