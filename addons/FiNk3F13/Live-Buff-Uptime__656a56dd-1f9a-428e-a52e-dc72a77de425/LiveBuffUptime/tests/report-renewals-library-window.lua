local env = dofile("tests/libcombat.lua")
local saved = env.saved()
saved.trackers = {{key = 1, id = 61771, unit = "player", x = 0, y = 0, scale = 1}}
ZO_SavedVars.NewAccountWide = function() return saved end
env.setCombat(false); env.setClock(90); env.setBuffs("player", {})
dofile("LiveBuffUptime.lua")
env.events[EVENT_ADD_ON_LOADED](nil, "LiveBuffUptime")
local function effect(time, change)
    env.setClock(time)
    env.setBuffs("player", {{61771, time, time + 15}})
    env.events[EVENT_EFFECT_CHANGED](nil, change, 1, "", "player", time, time + 15, 1, "icon", 0, 1, 0, 0, "Spieler", 1, 61771, 1)
end
env.setClock(100); env.setCombat(true)
env.callbacks[LIBCOMBAT_EVENT_MESSAGES](nil, 200000, LIBCOMBAT_MESSAGE_COMBATSTART)
effect(101, EFFECT_RESULT_GAINED)
env.setClock(102)
env.callbacks[LIBCOMBAT_EVENT_DAMAGE_OUT](nil, 202000)
env.setClock(105)
env.callbacks[LIBCOMBAT_EVENT_DAMAGE_OUT](nil, 205000)
effect(107, EFFECT_RESULT_UPDATED)
effect(109, EFFECT_RESULT_UPDATED)
env.setCombat(false)
effect(112, EFFECT_RESULT_UPDATED)
env.setClock(115)
env.callbacks[LIBCOMBAT_EVENT_FIGHTSUMMARY](nil, {starttime = 200000, endtime = 210000})
local report = assert(saved.lastUptimeReport)
local row = assert(report.buffs[1].members[1])
assert(row.received == 1, "Receipt before first damage belongs to the combat")
assert(row.renewed == 2, "Count combat renewals, not effects after the library combat end: " .. tostring(row.renewed))
assert(report.started == 102 and report.ended == 105, "Library damage window must remain unchanged")
assert(row.duration == 3, "Counter window must not extend the reference duration")
print("Partial library: counters use actual combat bounds, not damage bounds or delayed summary arrival")
