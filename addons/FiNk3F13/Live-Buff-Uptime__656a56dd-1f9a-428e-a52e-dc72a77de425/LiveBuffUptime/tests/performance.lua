local env = dofile("tests/addon.lua")
local Audit = LiveBuffUptimeDiagnostics
local clock, calls = 0, 0
local perf = Audit.NewPerformance(function() return clock end)
local inner = Audit.Profile(perf, "ESO-Ereignisse", function() clock = clock + 2 end)
local outer = Audit.Profile(perf, "Live-Update", function() calls = calls + 1; inner(); clock = clock + 5 end)
outer()
assert(calls == 1 and next(perf.buckets) == nil)
Audit.PerformanceEnabled(perf, true)
outer()
assert(perf.total == 7 and perf.buckets["Live-Update"].max == 7)
assert(perf.buckets["ESO-Ereignisse"].total == 2)
Audit.PerformanceFrame(perf, 0.016)
Audit.PerformanceFrame(perf, 0.06)
assert(perf.frames == 2 and perf.slowFrames == 1 and perf.maxFrameMS == 60)
local bad = Audit.Profile(perf, "ESO-Ereignisse", function() error("expected failure") end)
assert(not pcall(bad) and perf.depth == 0 and perf.buckets["ESO-Ereignisse"].errors == 1)
Audit.PerformanceEnabled(perf, false)
outer()
assert(perf.total == 7)
dofile("LiveBuffUptime.lua")
env.events[EVENT_ADD_ON_LOADED](nil, "LiveBuffUptime")
assert(not env.controls.LiveBuffUptimePerformanceFrames, "Profiler must not be installed in shipping addon")
env.events.tick()
print("Developer-only performance helpers: nested timing, frame gaps, error propagation and no shipping profiler passed")
