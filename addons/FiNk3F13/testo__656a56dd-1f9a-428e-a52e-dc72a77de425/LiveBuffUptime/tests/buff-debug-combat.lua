local setup = dofile("tests/group-effect-timers.lua")
local env = setup.env
local function finish(time)
    env.setClock(time)
    setup.callbacks[51](51, { unitIds = { player = 1 }, units = {} })
end
env.setClock(1000)
SLASH_COMMANDS["/lbu"]("buffdebug group 61771")
local from = #env.messages
setup.raw(1000, 2, 1, 1010)
assert(#env.messages == from, "Waiting debug must ignore out-of-combat buffs")
setup.begin(1000)
setup.raw(1000, 2, 1, 1010)
setup.damage(1100)
finish(1101)
assert(LiveBuffUptimeBuffDebug.active, "Combat end must keep the debug enabled")
setup.raw(1102, 2, 1, 1200)
SLASH_COMMANDS["/lbu"]("buffdebug group 61771")
local report = table.concat(env.messages, "\n", from + 1)
assert(report:find("group2: Buff 10.00s / Lebendzeit 100.00s = 10.00% | ESO erhalten 1", 1, true))
setup.begin(1200)
setup.raw(1200, 1, 1, 1220)
setup.damage(1300)
finish(1301)
from = #env.messages
SLASH_COMMANDS["/lbu"]("buffdebug group 61771")
report = table.concat(env.messages, "\n", from + 1)
assert(report:find("group2: Buff 0.00s / Lebendzeit 100.00s = 0.00% | ESO erhalten 0", 1, true), "Next combat must reset per-member counters")
assert(report:find("player: Buff 20.00s / Lebendzeit 100.00s = 20.00% | ESO erhalten 1", 1, true))
env.setClock(1400)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
setup.begin(1400)
setup.raw(1400, 1, 1, 0)
setup.damage(1410)
-- A query after the last damage must not inflate the final combat-only duration.
env.setClock(1415)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
finish(1416)
setup.raw(1417, 1, 1, 0)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
assert(env.messages[#env.messages - 1]:find("Buffzeit 10.00s", 1, true))
assert(env.messages[#env.messages - 1]:find("erhalten 1", 1, true))
assert(env.messages[#env.messages]:find("Kampf abgeschlossen", 1, true))
setup.begin(1500)
setup.raw(1500, 1, 1, 1505)
setup.damage(1510)
finish(1511)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
assert(env.messages[#env.messages - 1]:find("Buffzeit 5.00s", 1, true))
assert(env.messages[#env.messages - 1]:find("erhalten 1", 1, true))
print("Combat buff debug: waiting, automatic group/self reset, per-fight counters, frozen completion, post-combat exclusion and damage-end clipping passed")
