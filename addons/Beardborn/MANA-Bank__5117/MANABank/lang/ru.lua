local function plural(n, one, few, many)
    local m10, m100 = n % 10, n % 100
    if m10 == 1 and m100 ~= 11 then return one end
    if m10 >= 2 and m10 <= 4 and (m100 < 12 or m100 > 14) then return few end
    return many
end

