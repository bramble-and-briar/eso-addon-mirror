-- This environment owns the Crown Store. Reflow every future tooltip from its
-- source text and actual style width before the native section measures it.
local R = ESO_ARABIC_TEXT
if ZO_TooltipStyledObject and SecurePostHook then
    SecurePostHook(ZO_TooltipStyledObject, "FormatLabel", function(self, label, text, ...)
        if not R.HasArabic(text) then return end
        local width = self.GetWidthProperty and self:GetWidthProperty(...)
        if width == nil and self.GetInnerSecondaryDimension and self:IsVertical() then
            width = self:GetInnerSecondaryDimension()
        end
        local _, size, flags = label:GetFont():match("^(.-)|(%d+)|?(.*)$")
        size = tonumber(size) or 28
        local font = "EsoAR/fonts/ArabicUI.slug|" .. size .. "|" .. (flags or "soft-shadow-thin")
        label:SetFont(font)
        label.fontString = font
        label:SetModifyTextType(MODIFY_TEXT_TYPE_NONE)
        label:SetHorizontalAlignment(TEXT_ALIGN_RIGHT)
        if self.GetHeightProperty and self:GetHeightProperty(...) == nil then
            label:SetMaxLineCount(0)
        end
        local prepared = R.Prepare(text)
        if type(width) == "number" and width > 0 then
            label:SetWidth(width)
            local scale = label:GetScale()
            prepared = R.WrapVisual(R.JoinVisualLines(prepared), width, function(s)
                return label:GetStringWidth(s) / math.max(scale, 0.01)
            end)
        end
        label:SetText(prepared)
    end)
end
end
