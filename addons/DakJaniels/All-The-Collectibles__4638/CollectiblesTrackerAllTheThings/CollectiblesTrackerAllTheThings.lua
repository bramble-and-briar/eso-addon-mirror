        CompressCollectibleIds(collectibleIds),
        parentKey = sourceRow.parentKey,
        parentTitle = sourceRow.parentTitle,
        leafTitle = sourceRow.leafTitle,
        parentIcon = sourceRow.parentIcon,
        leafIcon = sourceRow.leafIcon,
        collectionsCategoryIndex = sourceRow.collectionsCategoryIndex,
        collectionsSubcategoryIndex = sourceRow.collectionsSubcategoryIndex,
        isChildlessCategory = sourceRow.isChildlessCategory,
        isUnreleased = sourceRow.isUnreleased,
        isNotImplementedGroup = sourceRow.isNotImplementedGroup,
    }
end

function CollectiblesTrackerAllTheThings.BuildThirdPartyTabData()
    local seen = BuildCollectiblesTrackerSeenIdSet()
    local crateSeen = CollectiblesTrackerAllTheThings.BuildCrateCollectibleIdSet()
    for collectibleId in pairs(crateSeen) do
        seen[collectibleId] = true
    end
    local storeSeen = CollectiblesTrackerAllTheThings.BuildStoreCollectibleIdSet()
    for collectibleId in pairs(storeSeen) do
        seen[collectibleId] = true
    end

    local leftoverIds = CollectLeftoverCollectibleIds(seen)
    local unreleasedIds = {}
    local invalidIds = {}
    local idsByTopLevel = {}

    for _, collectibleId in ipairs(leftoverIds) do
        if (CollectiblesTrackerAllTheThings.IsUnreleasedCollectibleIcon(GetCollectibleIcon(collectibleId))) then
            unreleasedIds[#unreleasedIds + 1] = collectibleId
        else
            local topLevelIndex, subCategoryIndex = GetCategoryInfoFromCollectibleId(collectibleId)
            if (topLevelIndex == nil) then
                invalidIds[#invalidIds + 1] = collectibleId
            else
                local idsBySubcategory = idsByTopLevel[topLevelIndex]
                if (idsBySubcategory == nil) then
                    idsBySubcategory = {}
                    idsByTopLevel[topLevelIndex] = idsBySubcategory
                end
                local subcategoryKey = subCategoryIndex or 0
                local bucketIds = idsBySubcategory[subcategoryKey]
                if (bucketIds == nil) then
                    bucketIds = {}
                    idsBySubcategory[subcategoryKey] = bucketIds
                end
                bucketIds[#bucketIds + 1] = collectibleId
            end
        end
    end

    local tabData =
    {
        {
            GetString(SI_COLLECTIBLESTRACKER_SOURCE_ALL),
            {},
        },
    }

    local function AppendTopLevelCategoryRows(topLevelIndex)
        local idsBySubcategory = idsByTopLevel[topLevelIndex]
        if (idsBySubcategory == nil) then
            return
        end

        local numSubcategories = GetNumSubcategoriesInCollectibleCategory(topLevelIndex) or 0
        local parentTitle = CollectiblesTrackerAllTheThings.GetCollectionsCategoryParentDisplayName(topLevelIndex)
        local sampleCollectibleIds = nil
        for _, bucketIds in pairs(idsBySubcategory) do
            sampleCollectibleIds = bucketIds
            break
        end
        local parentIcon = CollectiblesTrackerAllTheThings.GetCollectionsCategorySourceIcon(
            topLevelIndex,
            nil,
            sampleCollectibleIds
        )
        local parentKey = tostring(topLevelIndex)
        local isChildlessCategory = numSubcategories == 0
        local emittedSubcategory = {}

        local function AppendSubcategoryRow(subcategoryKey)
            local bucketIds = idsBySubcategory[subcategoryKey]
            if (bucketIds == nil or #bucketIds == 0) then
                return
            end
            emittedSubcategory[subcategoryKey] = true
            local subCategoryIndex = nil
            if (subcategoryKey > 0) then
                subCategoryIndex = subcategoryKey
            end
            local leafTitle
            if (subCategoryIndex ~= nil) then
                leafTitle = CollectiblesTrackerAllTheThings.GetCollectionsCategoryFormattedName(
                    topLevelIndex,
                    subCategoryIndex
                )
            else
                leafTitle = CollectiblesTrackerAllTheThings.GetCollectionsCategoryFormattedName(topLevelIndex, nil)
            end
            if (leafTitle == nil or leafTitle == "") then
                leafTitle = parentTitle
            end
            local leafIcon = CollectiblesTrackerAllTheThings.GetCollectionsCategorySourceIcon(
                topLevelIndex,
                subCategoryIndex,
                bucketIds
            )
            AppendCollectionsSourceRow(tabData, {
                collectibleIds = bucketIds,
                parentKey = parentKey,
                parentTitle = parentTitle,
                leafTitle = leafTitle,
                parentIcon = parentIcon,
                leafIcon = leafIcon,
                collectionsCategoryIndex = topLevelIndex,
                collectionsSubcategoryIndex = subcategoryKey,
                isChildlessCategory = isChildlessCategory and subcategoryKey == 0,
                isUnreleased = false,
            })
        end

        if (isChildlessCategory) then
            AppendSubcategoryRow(0)
        else
            AppendSubcategoryRow(0)
            for subIndex = 1, numSubcategories do
                AppendSubcategoryRow(subIndex)
            end
        end

        for _, subcategoryKey in ipairs(GetSortedNumericKeys(idsBySubcategory)) do
            if (not emittedSubcategory[subcategoryKey]) then
                AppendSubcategoryRow(subcategoryKey)
            end
        end
    end

    local emittedTopLevel = {}
    local numCategories = GetNumCollectibleCategories() or 0
    for topLevelIndex = 1, numCategories do
        emittedTopLevel[topLevelIndex] = true
        AppendTopLevelCategoryRows(topLevelIndex)
    end

    for _, topLevelIndex in ipairs(GetSortedNumericKeys(idsByTopLevel)) do
        if (not emittedTopLevel[topLevelIndex]) then
            AppendTopLevelCategoryRows(topLevelIndex)
        end
    end

    local notImplementedTitle = GetString(SI_COLLECTIBLES_TRACKER_ALL_THE_THINGS_NOT_IMPLEMENTED)
    local notImplementedIcon = CollectiblesTrackerAllTheThings.NOT_IMPLEMENTED_CATEGORY_ICON
    local function AppendNotImplementedLeaf(leafTitle, leafIcon, collectibleIds)
        if (collectibleIds == nil or #collectibleIds == 0) then
            return
        end
        AppendCollectionsSourceRow(tabData, {
            collectibleIds = collectibleIds,
            parentKey = CollectiblesTrackerAllTheThings.SOURCE_KEY_NOT_IMPLEMENTED,
            parentTitle = notImplementedTitle,
            leafTitle = leafTitle,
            parentIcon = notImplementedIcon,
            leafIcon = leafIcon,
            collectionsCategoryIndex = 0,
            collectionsSubcategoryIndex = 0,
            isChildlessCategory = false,
            isUnreleased = false,
            isNotImplementedGroup = true,
        })
    end

    AppendNotImplementedLeaf(
        GetString(SI_COLLECTIBLES_TRACKER_ALL_THE_THINGS_UNRELEASED),
        CollectiblesTrackerAllTheThings.UNRELEASED_COLLECTIBLE_ICON,
        unreleasedIds
    )
