function DungeonRatingFindBossReference(dungeonName,bossName)
  if type(dungeonName)~="string" or type(bossName)~="string" then return nil end
  local function norm(v)
    return string.lower(v):gsub("|c%x%x%x%x%x%x", ""):gsub("|r", ""):gsub("[^%w]", "")
  end
  local d=DungeonRatingBossIntelligence[string.lower(dungeonName)]
  if not d then
    for dungeon,entry in pairs(DungeonRatingBossIntelligence) do
      if norm(dungeon)==norm(dungeonName) then d=entry;break end
    end
  end
  if not d then return nil end
  local search=norm(bossName)
  for _,boss in ipairs(d.bosses) do
    if norm(boss.name)==search then return boss,d end
  end
  return nil
end
