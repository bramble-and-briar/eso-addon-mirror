local env = dofile("tests/addon.lua")
EFFECT_RESULT_GAINED, EFFECT_RESULT_UPDATED, EFFECT_RESULT_FADED = 1, 2, 3
env.setBuffs("player", {})
env.setClock(100)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
assert(LiveBuffUptimeBuffDebug.active)
LiveBuffUptimeBuffDebug.BeginFight(100)
local count = #env.messages
local function raw(time, change, slot, ends, ability)
    env.setClock(time)
    env.rawEvents[EVENT_EFFECT_CHANGED](nil, change, slot, "", "player", time, ends, 1, "icon", 0, 1, 0, 0, "Name", 1, ability or 61771, 0)
end
raw(105, 1, 1, 115)
assert(#env.messages == count, "Quick mode must record quietly")
env.setClock(110)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
assert(env.messages[#env.messages - 1]:find("Buffzeit 5.00s", 1, true))
assert(LiveBuffUptimeBuffDebug.active)
raw(110, 2, 1, 130)
raw(112, 1, 2, 118)
raw(116, 3, 1, 130)
env.setClock(120)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
local summary = env.messages[#env.messages - 1]
assert(summary:find("Buffzeit 13.00s", 1, true), "Union must respect early fade, refresh and missing fade expiry")
assert(summary:find("erhalten 2 / erneuert 1", 1, true))
assert(summary:find("jetzt inaktiv", 1, true))
env.setClock(121)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
assert(env.messages[#env.messages - 1]:find("Buffzeit 13.00s", 1, true), "Repeated query must not reset or double count")
env.setClock(300)
SLASH_COMMANDS["/lbu"]("buffdebug 61747")
LiveBuffUptimeBuffDebug.BeginFight(300)
raw(301, 1, 1, 0, 61747)
raw(305, 3, 1, 0, 61747)
env.setClock(310)
SLASH_COMMANDS["/lbu"]("buffdebug off")
assert(not LiveBuffUptimeBuffDebug.active)
assert(env.messages[#env.messages - 1]:find("Buffzeit 4.00s", 1, true), "Switching ID starts fresh; indefinite effects use fades")
env.setClock(400)
SLASH_COMMANDS["/lbu"]("buffdebug report")
assert(table.concat(env.messages, "\n", #env.messages - 4):find("Buffzeit 4.00s", 1, true), "Stopped duration must remain frozen")
env.setClock(500)
env.setBuffs("player", { { 61771, 490, 510 } })
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
LiveBuffUptimeBuffDebug.BeginFight(500)
LiveBuffUptimeBuffDebug.Snapshot(61771, 510, 1)
env.setClock(520)
SLASH_COMMANDS["/lbu"]("buffdebug 61771")
assert(env.messages[#env.messages - 1]:find("Buffzeit 10.00s", 1, true), "Start snapshot counts only time since enabling")
assert(env.messages[#env.messages - 1]:find("erhalten 0", 1, true))
print("Buff debug summaries: quiet ID command, ongoing queries, time union, refresh, early/missing fades, counter precision, reset, frozen stop and clipped snapshot passed")
