dofile("Core.lua")
local C = AddKillCounter.Core
local checks = 0
local function eq(actual, expected, message)
    checks = checks + 1
    assert(actual == expected, (message or "Mismatch") .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local stats = C.NewStats()
C.Record(stats, "20261109", "12:00:01")
C.Record(stats, "20261109", "12:00:02")
C.Record(stats, "20261110", "00:00:01")
eq(stats.total, 3, "Lifetime total")
eq(stats.days["20261109"].total, 2, "Previous day retained")
eq(stats.days["20261110"].total, 1, "New day starts separately")
eq(stats.days["20261109"].firstTime, "12:00:01", "First time")
eq(stats.days["20261109"].lastTime, "12:00:02", "Last time")
eq(stats.log, nil, "No individual history")
eq(stats.enemies, nil, "No per-enemy totals")
eq(C.GetDays(stats)[1], "20261110", "Newest day first")
eq(C.FormatDate("20260201"), "01.02.2026", "German date")
stats.log = {items = {{name = "Legacy NPC", character = "Legacy character"}}}
stats.enemies = {Wolf = {count = 3}}
stats.days["20261109"].enemies = {Wolf = {count = 2}}
C.RemoveDetails(stats)
eq(stats.log, nil, "Legacy history removed")
eq(stats.enemies, nil, "Legacy enemy totals removed")
eq(stats.days["20261109"].enemies, nil, "Legacy day names removed")
eq(stats.total, 3, "Migration preserves lifetime total")
eq(stats.days["20261109"].total, 2, "Migration preserves day total")
C.RemoveDetails(stats)
eq(stats.total, 3, "Migration is repeatable")
for i = 1, 20000 do C.Record(stats, "20261110", "12:00:00") end
eq(stats.total, 20003, "20,000 kills counted")
eq(stats.log, nil, "No history grows during counting")
eq(stats.enemies, nil, "No names grow during counting")
eq(C.DeleteDay(stats, "20261109"), true, "Old day can be deleted")
eq(stats.days["20261109"], nil, "Deleted day removed from archive")
eq(stats.total, 20003, "Deleting archive day preserves lifetime total")
eq(C.DeleteDay(stats, "20261109"), false, "Deleting missing day is harmless")
eq(C.DeleteDay(stats, "20261110"), true, "Current day can be deleted")
C.Record(stats, "20261110", "13:00:00")
eq(stats.days["20261110"].total, 1, "Current day restarts after deletion")
eq(stats.total, 20004, "Lifetime total continues after deleting today")
local tracker = C.NewTracker()
C.Observe(tracker, 17, "Skelett", 0)
eq(C.ResolveDeath(tracker, 17, "", 1), "Skelett", "Missing death name resolved by ID")
eq(C.ResolveDeath(tracker, 17, "Skelett", 2), nil, "Duplicate death ignored")
eq(C.ResolveDeath(tracker, 18, "Skelett", 2), "Skelett", "Same name different unit counts")
eq(C.ResolveDeath(tracker, 0, "Wolf", 2), nil, "Missing ID skipped")
eq(C.ResolveDeath(tracker, 19, "", 2), nil, "Unknown name skipped")
C.Observe(tracker, 20, "Wolf", 3)
eq(C.ResolveDeath(tracker, 20, "", 125), nil, "Stale fallback rejected")
C.Sweep(tracker, 140)
eq(next(tracker.seen), nil, "Observed IDs expire")
eq(next(tracker.dead), nil, "Death IDs expire")
eq(C.ResolveDeath(tracker, 17, "Skelett", 141), "Skelett", "ID reusable after expiry")
print("Core: " .. checks .. " checks passed")
