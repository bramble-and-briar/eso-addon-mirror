    private static void AppendGuildEvents(StringBuilder lua, IEnumerable<GuildEventConfig> events)
    {
        lua.AppendLine("            events = {");
        foreach (var guildEvent in events.OrderBy(guildEvent => guildEvent.GuildEventName, StringComparer.Ordinal))
        {
            const string indent = "                    ";
            lua.AppendLine("                {");
            lua.AppendLine($"{indent}guildEventId = {LuaString(guildEvent.GuildEventId)},");
            lua.AppendLine($"{indent}guildEventName = {LuaString(guildEvent.GuildEventName)},");
            AppendOptionalString(lua, indent, "megaserver", guildEvent.Megaserver);
            AppendOptionalNumber(lua, indent, "startsAt", guildEvent.StartsAt);
            AppendOptionalNumber(lua, indent, "endsAt", guildEvent.EndsAt);
            lua.AppendLine($"{indent}accessMode = {LuaString(guildEvent.AccessMode)},");
            AppendOptionalString(lua, indent, "esoGuildName", guildEvent.EsoGuildName);
            AppendOptionalString(lua, indent, "accessMegaserver", guildEvent.AccessMegaserver);
            lua.Append($"{indent}zoneIds = {{ ");
            lua.Append(string.Join(", ", guildEvent.ZoneIds.Order()));
            lua.AppendLine(" },");
            lua.AppendLine("                },");
        }
        lua.AppendLine("            },");
    }

    private static void AppendStringArray(
        StringBuilder lua,
        string indent,
        string field,
        IEnumerable<string> values)
    {
        lua.Append($"{indent}{field} = {{ ");
        lua.Append(string.Join(", ", values.Select(LuaString)));
        lua.AppendLine(" },");
    }

    private static void AppendOptionalString(
        StringBuilder lua,
        string indent,
        string field,
        string? value)
    {
        if (value is not null) lua.AppendLine($"{indent}{field} = {LuaString(value)},");
    }

    private static void AppendOptionalNumber<T>(
        StringBuilder lua,
        string indent,
        string field,
        T? value)
        where T : struct
    {
        if (value is not null) lua.AppendLine($"{indent}{field} = {value.Value},");
    }

    private static void AppendOptionalBoolean(
        StringBuilder lua,
        string indent,
        string field,
        bool? value)
    {
        if (value is not null) lua.AppendLine($"{indent}{field} = {LuaBoolean(value.Value)},");
    }

    private static string LuaBoolean(bool value) => value ? "true" : "false";

    private static string LuaString(string value)
    {
        var result = new StringBuilder(value.Length + 2).Append('"');
        foreach (var character in value)
        {
            switch (character)
            {
                case '\\': result.Append("\\\\"); break;
                case '"': result.Append("\\\""); break;
                case '\n': result.Append("\\n"); break;
                case '\r': result.Append("\\r"); break;
                case '\t': result.Append("\\t"); break;
                default:
                    if (character < 32)
                        result.Append('\\').Append(((int)character).ToString("D3", CultureInfo.InvariantCulture));
                    else
                        result.Append(character);
                    break;
            }
        }
        return result.Append('"').ToString();
    }
