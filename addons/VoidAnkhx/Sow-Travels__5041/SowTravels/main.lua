SOWTRAVELS = SOWTRAVELS or {}

function SOWTRAVELS.Travel(nodeId, destinationName)
    if type(nodeId) ~= "number" then
        d("|cFF5555Sow Trials: Invalid destination ID.|r")
        return
    end

    if type(FastTravelToNode) ~= "function" then
        d("|cFF5555Sow Trials: FastTravelToNode is unavailable.|r")
        return
    end

    d("|c66CCFFSow Trials: Travelling to " .. tostring(destinationName) .. "...|r")
    FastTravelToNode(nodeId)
end

