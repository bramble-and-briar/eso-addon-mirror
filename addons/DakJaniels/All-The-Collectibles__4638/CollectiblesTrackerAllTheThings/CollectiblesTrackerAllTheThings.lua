function CollectiblesTrackerAllTheThings.GetCrownCrateShortDisplayName(sourceDef)
    local crateName = CollectiblesTrackerAllTheThings.GetCrownCrateDisplayName(sourceDef)
    if (crateName == nil or crateName == "") then
        return crateName
    end

    local suffix = GetString(SI_COLLECTIBLES_TRACKER_ALL_THE_THINGS_CRATE_NAME_SUFFIX)
    if (suffix == nil or suffix == "") then
        return crateName
    end

    local suffixLength = string.len(suffix)
    local crateNameLength = string.len(crateName)
    if (crateNameLength <= suffixLength) then
        return crateName
    end
    if (string.sub(crateName, -suffixLength) == suffix) then
        return string.sub(crateName, 1, crateNameLength - suffixLength)
    end

    return crateName
end

