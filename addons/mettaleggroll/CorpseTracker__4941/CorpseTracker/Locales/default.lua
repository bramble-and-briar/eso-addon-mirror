if CT.english then return end -- String IDs already exist for this UI load.
local CreateStringId, GetString = ZO_CreateStringId, GetString
local globals = _G
CT.stringIds, CT.english = {}, {}
local function Add(key, text)
    local name = "CORPSETRACKER_" .. key
    CreateStringId(name, text)
    local id = globals[name]
    CT.stringIds[key], CT.english[key] = id, GetString(id)
end

