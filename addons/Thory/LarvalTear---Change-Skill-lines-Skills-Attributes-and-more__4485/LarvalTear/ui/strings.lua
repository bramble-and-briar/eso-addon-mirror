local function ReplaceParams(text, params)
    if type(text) ~= "string" then
        return ""
    end

    return (text:gsub("{([%w_]+)}", function(key)
        local value = type(params) == "table" and params[key] or nil
        if value == nil then
            return ""
        end

        return tostring(value)
    end))
end

function LTM_UI_STRINGS:GetText(key, params)
    local stringIdName = STRING_IDS[key]
    local stringId = type(stringIdName) == "string" and rawget(_G, stringIdName) or nil
    local text = type(GetString) == "function" and stringId ~= nil and GetString(stringId) or nil
    if type(text) ~= "string" or text == "" then
        text = key
    end

    return ReplaceParams(text, params)
end
